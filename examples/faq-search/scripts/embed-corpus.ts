/**
 * Embed the FAQ corpus at build time.
 *
 * Without this the dashboard has nothing to show until a 21.9 MB model has
 * downloaded — no rows, no database, no vector plot, just a spinner. The
 * corpus never changes between builds, so embedding it fourteen times in
 * every visitor's browser is work nobody needs to repeat.
 *
 * The sample queries are precomputed for the same reason: somebody should be
 * able to open the dashboard, click a query and watch the whole pipeline run
 * without downloading anything. A query they type themselves is the one case
 * that genuinely cannot be precomputed, and that is when the model loads.
 *
 *   node --experimental-strip-types scripts/embed-corpus.ts
 */
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { pipeline } from '@huggingface/transformers'
import { docText, FAQ } from '../src/search/faq-data.ts'
import { SAMPLE_QUERIES } from '../src/search/sample-queries.ts'

const MODEL = 'Xenova/all-MiniLM-L6-v2'
const DTYPE = 'q8'
const OUT = resolve(import.meta.dirname, '../src/search/corpus-vectors.ts')

const extract = await pipeline('feature-extraction', MODEL, { dtype: DTYPE })

const encode = async (texts: string[]) => {
  const out = await extract(texts, { pooling: 'mean', normalize: true })
  const dims = out.dims.at(-1) as number
  const data = Float32Array.from(out.data as Float32Array)
  if (data.length !== texts.length * dims) {
    throw new Error(`expected ${texts.length} x ${dims} floats, got ${data.length}`)
  }
  return {
    dims,
    base64: Buffer.from(data.buffer, data.byteOffset, data.byteLength).toString('base64'),
    bytes: data.byteLength,
  }
}

const corpus = await encode(FAQ.map(docText))
const samples = await encode([...SAMPLE_QUERIES])
if (samples.dims !== corpus.dims) throw new Error('dimension mismatch between corpus and samples')
const dims = corpus.dims

writeFileSync(
  OUT,
  `// Generated by scripts/embed-corpus.ts — do not edit by hand.
// Rebuild after changing faq-data.ts or sample-queries.ts:
//   npm run embed -w faq-search
//
// ${FAQ.length} corpus entries and ${SAMPLE_QUERIES.length} sample queries, each
// ${dims} float32 dimensions, base64. Shipped so the dashboard opens with its
// database, rows and vector plot already populated, and so a visitor can run
// the whole pipeline on a sample query without downloading the encoder.

/** The model these came from. A query embedded by anything else is not comparable. */
export const CORPUS_MODEL = ${JSON.stringify(`${MODEL} (${DTYPE})`)}

export const CORPUS_DIMS = ${dims}

export const CORPUS_COUNT = ${FAQ.length}

const CORPUS_PACKED =
  '${corpus.base64}'

const SAMPLE_PACKED =
  '${samples.base64}'

function unpack(packed: string, count: number): Float32Array[] {
  const bytes = Uint8Array.from(atob(packed), (c) => c.charCodeAt(0))
  const all = new Float32Array(bytes.buffer, bytes.byteOffset, bytes.byteLength / 4)
  return Array.from({ length: count }, (_, i) =>
    all.slice(i * CORPUS_DIMS, (i + 1) * CORPUS_DIMS),
  )
}

// Decoded once, lazily: ${(corpus.bytes / 1024).toFixed(1)} KB and ${(samples.bytes / 1024).toFixed(1)} KB of float32.
let corpusCache: Float32Array[] | null = null
let sampleCache: Float32Array[] | null = null

export function corpusVectors(): Float32Array[] {
  corpusCache ??= unpack(CORPUS_PACKED, CORPUS_COUNT)
  return corpusCache
}

/** In the order of SAMPLE_QUERIES. */
export function sampleVectors(): Float32Array[] {
  sampleCache ??= unpack(SAMPLE_PACKED, ${SAMPLE_QUERIES.length})
  return sampleCache
}
`,
)

console.log(
  `wrote ${OUT} — ${FAQ.length} x ${dims} corpus + ${SAMPLE_QUERIES.length} samples, ` +
    `${((corpus.base64.length + samples.base64.length) / 1024).toFixed(1)} KB base64`,
)
